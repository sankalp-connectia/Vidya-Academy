export function applyWordPressContent(content = {}) {
  if (!content || typeof content !== "object") return;
  if (Object.prototype.hasOwnProperty.call(content, "aboutImages")) aboutImages = content.aboutImages;
  if (Object.prototype.hasOwnProperty.call(content, "leaders")) leaders = content.leaders;
  if (Object.prototype.hasOwnProperty.call(content, "statement")) statement = content.statement;
  if (Object.prototype.hasOwnProperty.call(content, "outerRing")) outerRing = content.outerRing;
  if (Object.prototype.hasOwnProperty.call(content, "conceptRing")) conceptRing = content.conceptRing;
  if (Object.prototype.hasOwnProperty.call(content, "experienceRing")) experienceRing = content.experienceRing;
  if (Object.prototype.hasOwnProperty.call(content, "learnerDimensions")) learnerDimensions = content.learnerDimensions;
  if (Object.prototype.hasOwnProperty.call(content, "events")) events = content.events;
  if (Object.prototype.hasOwnProperty.call(content, "aboutCopy")) aboutCopy = content.aboutCopy;
}
