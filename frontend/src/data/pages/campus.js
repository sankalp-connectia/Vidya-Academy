export function applyWordPressContent(content = {}) {
  if (!content || typeof content !== "object") return;
  if (Object.prototype.hasOwnProperty.call(content, "introText")) introText = content.introText;
  if (Object.prototype.hasOwnProperty.call(content, "marqueeImages")) marqueeImages = content.marqueeImages;
  if (Object.prototype.hasOwnProperty.call(content, "groundsImages")) groundsImages = content.groundsImages;
  if (Object.prototype.hasOwnProperty.call(content, "heroImages")) heroImages = content.heroImages;
  if (Object.prototype.hasOwnProperty.call(content, "FALLBACK_IMAGE")) FALLBACK_IMAGE = content.FALLBACK_IMAGE;
  if (Object.prototype.hasOwnProperty.call(content, "FALLBACK_BUILDING_IMAGE")) FALLBACK_BUILDING_IMAGE = content.FALLBACK_BUILDING_IMAGE;
  if (Object.prototype.hasOwnProperty.call(content, "buildingMarqueeImages")) buildingMarqueeImages = content.buildingMarqueeImages;
  if (Object.prototype.hasOwnProperty.call(content, "buildingImages")) buildingImages = content.buildingImages;
  if (Object.prototype.hasOwnProperty.call(content, "campusFeatureImage")) campusFeatureImage = content.campusFeatureImage;
  if (Object.prototype.hasOwnProperty.call(content, "campusStats")) campusStats = content.campusStats;
  if (Object.prototype.hasOwnProperty.call(content, "campusCopy")) campusCopy = content.campusCopy;
  if (Object.prototype.hasOwnProperty.call(content, "upcomingCampus")) upcomingCampus = content.upcomingCampus;
}
