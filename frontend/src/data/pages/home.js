export function applyWordPressContent(content = {}) {
  if (!content || typeof content !== "object") return;
  if (Object.prototype.hasOwnProperty.call(content, "galleryImages")) galleryImages = content.galleryImages;
  if (Object.prototype.hasOwnProperty.call(content, "faqItems")) {
    faqItems = content.faqItems.filter((item) => item && item.status !== "draft");
  }
  if (Object.prototype.hasOwnProperty.call(content, "lifeCards")) lifeCards = content.lifeCards;
  if (Object.prototype.hasOwnProperty.call(content, "wayItems")) wayItems = content.wayItems;
  if (Object.prototype.hasOwnProperty.call(content, "fallbackImage")) fallbackImage = content.fallbackImage;
  if (Object.prototype.hasOwnProperty.call(content, "facts")) facts = content.facts;
  if (Object.prototype.hasOwnProperty.call(content, "programs")) programs = content.programs;
  if (Object.prototype.hasOwnProperty.call(content, "homeCopy")) homeCopy = content.homeCopy;
  if (Object.prototype.hasOwnProperty.call(content, "admissionFormCopy")) admissionFormCopy = content.admissionFormCopy;
  if (Object.prototype.hasOwnProperty.call(content, "homeMedia")) homeMedia = content.homeMedia;
}
